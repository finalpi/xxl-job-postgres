-- ================== job group and registry ==================

CREATE TABLE IF NOT EXISTS xxl_job_group
(
    id                    INT                 NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    app_name              VARCHAR(64)         NOT NULL,
    name                  VARCHAR(64)         NOT NULL,
    address_type          SMALLINT             NOT NULL DEFAULT 0,
    address_list          TEXT                DEFAULT NULL,
    access_token          VARCHAR(255)        DEFAULT NULL,
    update_time           TIMESTAMP(3)            DEFAULT NULL,
    PRIMARY KEY (id),
    UNIQUE (app_name)
);

CREATE TABLE IF NOT EXISTS xxl_job_registry
(
    id                    BIGINT              NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    registry_group        VARCHAR(50)         NOT NULL,
    registry_key          VARCHAR(255)        NOT NULL,
    registry_value        VARCHAR(255)        NOT NULL,
    update_time           TIMESTAMP(3)            DEFAULT NULL,
    PRIMARY KEY (id),
    UNIQUE (registry_group, registry_key, registry_value)
);

-- ================== job info ==================

CREATE TABLE IF NOT EXISTS xxl_job_info
(
    id                        INT                 NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    job_group                 INT                 NOT NULL,
    name                      VARCHAR(255)        NOT NULL,
    author                    VARCHAR(64)         DEFAULT NULL,
    alarm_email               VARCHAR(255)        DEFAULT NULL,
    schedule_type             VARCHAR(50)         NOT NULL DEFAULT 'NONE',
    schedule_conf             VARCHAR(128)        DEFAULT NULL,
    misfire_strategy          VARCHAR(50)         NOT NULL DEFAULT 'DO_NOTHING',
    executor_route_strategy   VARCHAR(50)         DEFAULT NULL,
    executor_handler          VARCHAR(255)        DEFAULT NULL,
    executor_param            TEXT                DEFAULT NULL,
    executor_block_strategy   VARCHAR(50)         DEFAULT NULL,
    executor_timeout          INT                 NOT NULL DEFAULT 0,
    executor_fail_retry_count INT                 NOT NULL DEFAULT 0,
    glue_type                 VARCHAR(50)         NOT NULL,
    glue_source               TEXT          DEFAULT NULL,
    glue_remark               VARCHAR(128)        DEFAULT NULL,
    glue_updatetime           TIMESTAMP(3)            DEFAULT NULL,
    child_jobid               VARCHAR(255)        DEFAULT NULL,
    trigger_status            SMALLINT             NOT NULL DEFAULT 0,
    trigger_last_time         BIGINT              NOT NULL DEFAULT 0,
    trigger_next_time         BIGINT              NOT NULL DEFAULT 0,
    add_time                  TIMESTAMP(3)            DEFAULT NULL,
    update_time               TIMESTAMP(3)            DEFAULT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS xxl_job_logglue
(
    id                        INT                 NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    job_id                    INT                 NOT NULL,
    glue_type                 VARCHAR(50)         DEFAULT NULL,
    glue_source               TEXT          DEFAULT NULL,
    glue_remark               VARCHAR(128)        NOT NULL,
    add_time                  TIMESTAMP(3)            DEFAULT NULL,
    update_time               TIMESTAMP(3)            DEFAULT NULL,
    PRIMARY KEY (id)
);

-- ================== job log and report ==================

CREATE TABLE IF NOT EXISTS xxl_job_log
(
    id                        BIGINT              NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    job_group                 INT                 NOT NULL,
    job_id                    INT                 NOT NULL,
    executor_address          VARCHAR(255)        DEFAULT NULL,
    executor_handler          VARCHAR(255)        DEFAULT NULL,
    executor_param            TEXT                DEFAULT NULL,
    executor_sharding_param   VARCHAR(20)         DEFAULT NULL,
    executor_fail_retry_count INT                 NOT NULL DEFAULT 0,
    trigger_time              TIMESTAMP(3)            NOT NULL DEFAULT LOCALTIMESTAMP,
    trigger_code              INT                 NOT NULL,
    trigger_msg               TEXT                DEFAULT NULL,
    handle_time               TIMESTAMP(3)            DEFAULT NULL,
    handle_code               INT                 NOT NULL,
    handle_msg                TEXT                DEFAULT NULL,
    alarm_status              SMALLINT             NOT NULL DEFAULT 0,
    PRIMARY KEY (id, trigger_time)
) PARTITION BY RANGE (trigger_time);


CREATE INDEX IF NOT EXISTS xxl_job_log_i_trigger_time ON xxl_job_log (trigger_time);
CREATE INDEX IF NOT EXISTS xxl_job_log_i_handle_code ON xxl_job_log (handle_code);
CREATE INDEX IF NOT EXISTS xxl_job_log_i_job_group ON xxl_job_log (job_group);
CREATE INDEX IF NOT EXISTS xxl_job_log_i_job_id ON xxl_job_log (job_id);
CREATE INDEX IF NOT EXISTS xxl_job_log_i_alarm_status ON xxl_job_log (alarm_status);

CREATE TABLE IF NOT EXISTS xxl_job_log_report
(
    id                    INT             NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    trigger_day           TIMESTAMP(3)        DEFAULT NULL,
    running_count         INT             NOT NULL DEFAULT 0,
    suc_count             INT             NOT NULL DEFAULT 0,
    fail_count            INT             NOT NULL DEFAULT 0,
    update_time           TIMESTAMP(3)        DEFAULT NULL,
    PRIMARY KEY (id),
    UNIQUE (trigger_day)
);

-- ================== lock ==================

CREATE TABLE IF NOT EXISTS xxl_job_lock
(
    lock_name VARCHAR(50) NOT NULL,
    PRIMARY KEY (lock_name)
);

-- ================== user ==================

CREATE TABLE IF NOT EXISTS xxl_job_user
(
    id                INT                 NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    username          VARCHAR(50)         NOT NULL,
    password          VARCHAR(100)        NOT NULL,
    token             VARCHAR(100)        DEFAULT NULL,
    role              SMALLINT             NOT NULL,
    permission        VARCHAR(255)        DEFAULT NULL,
    PRIMARY KEY (id),
    UNIQUE (username)
);


